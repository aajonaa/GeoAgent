"""Approved unit-metadata regression only. No native/scientific engine is run.

The expected maps below are literal physical unit oracles, not generated by
the runtime mapper. No external packages, dependency skips or installs.
"""
from __future__ import annotations

import ast
from copy import deepcopy
import importlib
import json
import os
from pathlib import Path
import sys
import types
import unittest

GROUP = Path(__file__).resolve().parents[1]
ROOT = GROUP.parents[4]
SUPPORT = ROOT / "geological_agent/geology/expansion501_spatial_support"
package = types.ModuleType("_spatial_units_r2")
package.__path__ = [str(SUPPORT)]
sys.modules[package.__name__] = package
native = importlib.import_module(package.__name__ + ".native")
ContractError = importlib.import_module(package.__name__ + ".common").ContractError

HAG = "GeoSpatialPointCloudHeightAboveGround"
TREE = "GeoSpatialIndividualTreeSegmentation"
GROUND = "GeoSpatialPointCloudGroundClassification"
MORPH = "GeoSpatialPointCloudMorphologyDescriptors"
EXPECTED = {
    HAG: {"X":"m", "Y":"m", "Z":"m", "PointId":"input_zero_based",
          "Classification":"dimensionless_label", "HeightAboveGround":"m"},
    TREE: {"X":"m", "Y":"m", "Z":"m", "PointId":"input_zero_based",
           "HeightAboveGround":"m", "ClusterID":"dimensionless_label"},
    GROUND: {"X":"m", "Y":"m", "Z":"m", "PointId":"input_zero_based",
             "Classification":"dimensionless_label"},
    MORPH: {"X":"m", "Y":"m", "Z":"m", "PointId":"input_zero_based",
            "Linearity":"dimensionless", "Planarity":"dimensionless",
            "Scattering":"dimensionless", "Verticality":"dimensionless"},
}


def invariant_contracts(specs):
    result = {}
    for tool, spec in specs.items():
        output = deepcopy(spec["output_schema"])
        output["properties"].pop("units")
        output["required"] = [key for key in output["required"] if key != "units"]
        result[tool] = {"input_schema":spec["input_schema"], "output_without_units":output,
                        "requirements":spec["requirements"], "numeric_oracle":spec["numeric_oracle"]}
    return result


class ColumnUnitRegression(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.specs = json.loads((GROUP / "pending-contracts.json").read_text(encoding="utf-8"))

    def test_hag_classification_is_not_metres(self):
        self.assertEqual(native._pdal_column_units(list(EXPECTED[HAG])), EXPECTED[HAG])

    def test_tree_height_is_not_dimensionless(self):
        self.assertEqual(native._pdal_column_units(list(EXPECTED[TREE])), EXPECTED[TREE])

    def test_other_pdal_columns_keep_physical_units(self):
        for tool in (GROUND, MORPH):
            with self.subTest(tool=tool):
                self.assertEqual(native._pdal_column_units(list(EXPECTED[tool])), EXPECTED[tool])

    def test_unknown_column_has_no_guessed_unit(self):
        with self.assertRaises(ContractError) as caught:
            native._pdal_column_units(["X", "UnreviewedFeature"])
        self.assertEqual(caught.exception.code, "invalid_result")

    def test_generated_closed_unit_schemas_match_literal_oracles(self):
        for tool, expected in EXPECTED.items():
            with self.subTest(tool=tool):
                schema = self.specs[tool]["output_schema"]["properties"]["units"]
                self.assertEqual(schema["type"], "object")
                self.assertIs(schema["additionalProperties"], False)
                self.assertEqual(set(schema["required"]), set(expected))
                self.assertEqual({key:value["const"] for key,value in schema["properties"].items()}, expected)
                self.assertNotIn("features", schema["properties"])

    def test_legacy_inputs_are_preserved_not_used_as_column_units(self):
        self.assertEqual(self.specs[HAG]["input_schema"]["properties"]["feature_unit"]["const"], "m")
        self.assertEqual(self.specs[TREE]["input_schema"]["properties"]["feature_unit"]["const"], "dimensionless")

    def test_adapter_wires_actual_columns_to_unit_mapper(self):
        tree = ast.parse((SUPPORT / "native.py").read_text(encoding="utf-8"))
        function = next(node for node in tree.body if isinstance(node, ast.FunctionDef) and node.name == "_pdal_result")
        values = [node.value for node in ast.walk(function) if isinstance(node, ast.keyword) and node.arg == "units"]
        self.assertEqual(len(values), 1)
        self.assertIsInstance(values[0], ast.Call)
        self.assertEqual(values[0].func.id, "_pdal_column_units")
        self.assertEqual([argument.id for argument in values[0].args], ["fields"])

    def test_no_numeric_oracle_requirement_or_nonunit_schema_change(self):
        baseline_path = os.environ.get("SPATIAL_UNITFIX_BASELINE")
        self.assertIsNotNone(baseline_path, "Run through flow_units_r2.py to preserve the pre-generation snapshot")
        baseline = json.loads(Path(baseline_path).read_text(encoding="utf-8"))
        self.assertEqual(invariant_contracts(self.specs), baseline)

    def test_delivery_and_source_counts_are_honest(self):
        delivery = json.loads((GROUP / "delivery-files.json").read_text(encoding="utf-8"))["files"]
        prefix = GROUP.relative_to(ROOT).as_posix()
        for suffix in ("unitfix-handoff.md", "acceptance/test_units_r2.py", "acceptance/flow_units_r2.py"):
            self.assertIn(prefix + "/" + suffix, delivery)
        helpers = {p for p in delivery if p.startswith("geological_agent/geology/expansion501_spatial_support/")}
        self.assertEqual(helpers, {"geological_agent/geology/expansion501_spatial_support/" + p
                                  for p in ("common.py", "grass_task.py", "landlab_state.py", "native.py")})
        status = json.loads((GROUP / "resolution-status.json").read_text(encoding="utf-8"))
        self.assertEqual(len(self.specs), 11)
        self.assertEqual(status["scientific_adapters_still_incomplete"], 8)
        self.assertEqual(status["new_catalog_tools"], 0)
        self.assertEqual(status["new_accepted"], 0)
        self.assertTrue(all(spec["formal_eligible"] is False for spec in self.specs.values()))


if __name__ == "__main__":
    result = unittest.main(verbosity=2, exit=False).result
    report = {"scope":"unit_metadata_regression_only", "tests_run":result.testsRun,
              "failures":len(result.failures), "errors":len(result.errors), "skipped":len(result.skipped),
              "native_scientific_tests_run":0, "new_accepted":0, "new_deployed":0}
    destination = os.environ.get("SPATIAL_UNITFIX_REPORT")
    if destination:
        Path(destination).write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(report))
    raise SystemExit(0 if result.wasSuccessful() and not result.skipped else 1)
